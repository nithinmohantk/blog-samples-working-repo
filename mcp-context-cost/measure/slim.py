"""Ways to make a tool definition smaller before it is sent to a model, from safe to aggressive.

Only the first is free. Schema titles and the $schema marker are generated by tooling and carry nothing
a model needs. Everything after that removes text a model reads, and the lab cannot measure what that
does to tool selection, so each step should be tested with the agent that will use it.
"""
from __future__ import annotations

import copy
import re
from typing import Any

GENERATED = ("title", "$schema")
SENTENCE_END = re.compile(r"(?<=[.!?])\s")


def walk(schema: Any, visit) -> Any:
    """Apply visit to every schema object, leaving the names of properties alone."""
    if isinstance(schema, list):
        return [walk(item, visit) for item in schema]
    if not isinstance(schema, dict):
        return schema
    result = {}
    for key, value in visit(dict(schema)).items():
        if key in ("properties", "$defs", "definitions", "patternProperties") and isinstance(value, dict):
            result[key] = {name: walk(child, visit) for name, child in value.items()}  # keys here are names, not keywords
        else:
            result[key] = walk(value, visit)
    return result


def without(*keywords: str):
    def visit(node: dict[str, Any]) -> dict[str, Any]:
        return {key: value for key, value in node.items() if key not in keywords}
    return visit


def first_sentence(text: str) -> str:
    return SENTENCE_END.split(text.strip().replace("\n", " "), maxsplit=1)[0] if text else text


def strip_generated(tool: dict[str, Any]) -> dict[str, Any]:
    """Level 1: remove schema titles and $schema. Nothing a model relies on is lost."""
    slim = copy.deepcopy(tool)
    slim["inputSchema"] = walk(slim.get("inputSchema", {}), without(*GENERATED))
    return slim


def short_description(tool: dict[str, Any]) -> dict[str, Any]:
    """Level 2: level 1, and keep only the first sentence of the tool description."""
    slim = strip_generated(tool)
    slim["description"] = first_sentence(slim.get("description", ""))
    return slim


def bare_schema(tool: dict[str, Any]) -> dict[str, Any]:
    """Level 3: level 2, and drop parameter descriptions and defaults. Names and types are all that is left."""
    slim = short_description(tool)
    slim["inputSchema"] = walk(slim["inputSchema"], without("description", "default"))
    return slim


LEVELS = {"1 strip generated fields": strip_generated, "2 first-sentence descriptions": short_description, "3 names and types only": bare_schema}
